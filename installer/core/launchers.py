"""Environment, launchers, desktop/Start-Menu shortcuts and uninstall entry."""

from __future__ import annotations

import json
import os
import shutil
from pathlib import Path

from .detect import SystemInfo
from .paths import InstallPaths, runtime_search_path
from .plan import Selection
from .progress import Progress
from .util import ensure_dir, is_windows, run, write_text


def launcher_env(
    paths: InstallPaths,
    *,
    data_dir: Path | None = None,
    device: str,
    breeze_de: bool = False,
    breeze_de_cpu: bool = False,
) -> dict[str, str]:
    """Environment shared by the Linux/Windows launchers and verification."""
    env = {
        "DRAMA_LLAMA_DATA": str(data_dir or paths.data),
        "PYTHONUTF8": "1",
        "PYTHONIOENCODING": "utf-8",
        "PYTHONUNBUFFERED": "1",
        "BETTERSUNO_MCP_DIR": str(paths.app / "third_party" / "bettersuno-mcp"),
    }
    if device == "cpu":
        env["CUDA_VISIBLE_DEVICES"] = ""
    if breeze_de:
        env["BREEZE_DE_URL"] = "http://127.0.0.1:8137"
        if breeze_de_cpu or device == "cpu":
            env["BREEZE_DE_CPU"] = "1"
    return env


def _launch_script(paths: InstallPaths, env: dict[str, str], system: str) -> str:
    runtime_paths = [str(path) for path in runtime_search_path(paths, system=system)]
    return f'''#!/usr/bin/env python3
"""Generated by the Drama Llama installer. Do not edit by hand."""
from __future__ import annotations

import os
import sys

APP = {str(paths.app)!r}
ENVIRONMENT = {json.dumps(env, indent=2, ensure_ascii=False)}
RUNTIME_PATH = {runtime_paths!r}

for key, value in ENVIRONMENT.items():
    os.environ.setdefault(key, value)
os.environ["PATH"] = os.pathsep.join(RUNTIME_PATH + [os.environ.get("PATH", "")])
sys.path.insert(0, os.path.join(APP, "src"))
os.chdir(APP)

argv = sys.argv[1:]
if not argv or argv[0].startswith("-"):
    argv = ["ui", *argv]
sys.argv = ["drama-llama", *argv]

from drama_studio.cli import main  # noqa: E402

raise SystemExit(main())
'''


def _shell_quote(value: str | Path) -> str:
    return '"' + str(value).replace('"', '\\"') + '"'


def _linux_desktop(paths: InstallPaths) -> str:
    python = paths.python(system="linux")
    return f"""[Desktop Entry]
Type=Application
Name=Drama Llama
Comment=Turn a script into an audio drama
Exec={_shell_quote(python)} {_shell_quote(paths.prefix / "launch.py")} ui
Icon=drama-llama
Terminal=false
Categories=AudioVideo;Audio;Utility;
StartupNotify=true
"""


def _windows_cmd(paths: InstallPaths, env: dict[str, str]) -> str:
    lines = ["@echo off", "setlocal"]
    for key, value in env.items():
        lines.append(f'set "{key}={value}"')
    path = ";".join(
        [str(paths.bin), str(paths.node_dir), str(paths.venv / "Scripts"), "%PATH%"]
    )
    lines.append(f'set "PATH={path}"')
    lines.append(f'"{paths.python(system="windows")}" "{paths.prefix / "launch.py"}" %*')
    lines.append("endlocal")
    return "\r\n".join(lines) + "\r\n"


def _windows_shortcut_script(shortcut: Path, paths: InstallPaths) -> str:
    def ps(value: str) -> str:
        return "'" + value.replace("'", "''") + "'"

    arguments = '"' + str(paths.prefix / "launch.py") + '" ui'
    return (
        "$ws = New-Object -ComObject WScript.Shell\n"
        f"$s = $ws.CreateShortcut({ps(str(shortcut))})\n"
        f"$s.TargetPath = {ps(str(paths.pythonw(system='windows')))}\n"
        f"$s.Arguments = {ps(arguments)}\n"
        f"$s.WorkingDirectory = {ps(str(paths.prefix))}\n"
        f"$s.IconLocation = {ps(str(paths.pythonw(system='windows')))}\n"
        "$s.Description = 'Drama Llama audio drama studio'\n"
        "$s.Save()\n"
    )


def _windows_uninstall_cmd(paths: InstallPaths) -> str:
    python = paths.python(system="windows")
    return (
        "@echo off\r\n"
        "setlocal\r\n"
        f'set "PYTHONPATH={paths.app}"\r\n'
        "set PYTHONUTF8=1\r\n"
        f'"{python}" -m installer --headless --uninstall --yes '
        f'--prefix "{paths.prefix}" --keep-data %*\r\n'
        "pause\r\n"
    )


def write_launchers(
    paths: InstallPaths,
    pins: dict,
    selection: Selection,
    system: SystemInfo,
    progress: Progress,
    *,
    device: str,
    breeze_de_cpu: bool = False,
    state: dict | None = None,
) -> dict[str, str]:
    del pins  # kept in the signature for callers that only have the pin bundle
    env = launcher_env(
        paths,
        device=device,
        breeze_de=selection.has("breeze-de"),
        breeze_de_cpu=breeze_de_cpu,
    )
    progress.update("launchers", 0.1, "Writing the launcher…")
    launch = paths.prefix / "launch.py"
    write_text(launch, _launch_script(paths, env, system.os_name))
    if not is_windows(system.os_name):
        launch.chmod(0o755)

    shortcuts: list[Path] = []
    home = Path.home()
    if is_windows(system.os_name):
        write_text(paths.prefix / "drama-llama.cmd", _windows_cmd(paths, env))
        write_text(paths.prefix / "uninstall.cmd", _windows_uninstall_cmd(paths))
        start_menu = (
            Path(os.environ.get("APPDATA", home / "AppData" / "Roaming"))
            / "Microsoft"
            / "Windows"
            / "Start Menu"
            / "Programs"
        )
        ensure_dir(start_menu)
        shortcut = start_menu / "Drama Llama.lnk"
        script = _windows_shortcut_script(shortcut, paths)
        result = run(["powershell", "-NoProfile", "-Command", script], timeout=120)
        if result.returncode == 0 and shortcut.is_file():
            shortcuts.append(shortcut)
        else:
            progress.log("warning: could not create the Start Menu shortcut")
    else:
        ensure_dir(paths.bin)
        wrapper = paths.bin / "drama-llama"
        write_text(
            wrapper,
            "#!/usr/bin/env bash\n"
            f'exec "{paths.python(system="linux")}" "{launch}" "$@"\n',
        )
        wrapper.chmod(0o755)
        breeze_wrapper = paths.bin / "drama-llama-breeze-de"
        write_text(
            breeze_wrapper,
            "#!/usr/bin/env bash\n"
            f'exec "{paths.python(system="linux")}" -m drama_studio.cli breeze-de "$@"\n',
        )
        breeze_wrapper.chmod(0o755)

        applications = home / ".local" / "share" / "applications"
        ensure_dir(applications)
        desktop = applications / "drama-llama.desktop"
        write_text(desktop, _linux_desktop(paths))
        shortcuts.append(desktop)
        icons = home / ".local" / "share" / "icons" / "hicolor" / "256x256" / "apps"
        ensure_dir(icons)
        source_icon = paths.app / "web" / "public" / "llogo.png"
        icon = icons / "drama-llama.png"
        if source_icon.is_file():
            shutil.copy2(source_icon, icon)
            shortcuts.append(icon)
        binary_link = home / ".local" / "bin" / "drama-llama"
        ensure_dir(binary_link.parent)
        if binary_link.is_symlink() or not binary_link.exists():
            if binary_link.is_symlink():
                binary_link.unlink()
            binary_link.symlink_to(wrapper)
            shortcuts.append(binary_link)
        else:
            progress.log(f"warning: {binary_link} already exists and was left untouched")

    if state is not None:
        from .state import add_shortcut

        for shortcut in shortcuts:
            add_shortcut(state, shortcut)
    progress.update("launchers", 1.0, "Launchers and shortcuts created")
    return env
